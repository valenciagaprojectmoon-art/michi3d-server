import WebSocket from "ws";
let fails = 0; const ok = (c, m) => { console.log((c ? "OK   " : "FAIL ") + m); if (!c) fails++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function create(boardConfig, ip) {
  const ws = new WebSocket("ws://localhost:8096", { headers: { "x-forwarded-for": ip } });
  const inbox = []; ws.on("message", (d) => inbox.push(JSON.parse(d.toString())));
  await new Promise((r) => ws.on("open", r));
  ws.send(JSON.stringify({ type: "create_room", playerName: "A", acceptedTerms: "2026-10-09", ...(boardConfig ? { boardConfig } : {}) }));
  await sleep(300); ws.close();
  const m = inbox.find((x) => x.type === "room_created");
  return m?.state?.game;
}
const d = await create(undefined, "10.9.0.1");
ok(d?.boardConfig.size === 3 && d.boardConfig.lineLength === 3 && d.board.length === 27, "sin configuración: 3x3x3, línea 3, 27 casillas");
const a = await create({ size: 4, lineLength: 3 }, "10.9.0.2");
ok(a?.boardConfig.size === 4 && a.boardConfig.lineLength === 3 && a.board.length === 64, "cubo 4, línea 3: 64 casillas llegan al cliente");
const b = await create({ size: 99, lineLength: 99 }, "10.9.0.3");
ok(b?.boardConfig.size === 6 && b.boardConfig.lineLength === 6 && b.board.length === 216, "cubo 99 se limita a 6 (216 casillas)");
const c = await create({ size: 1, lineLength: 1 }, "10.9.0.4");
ok(c?.boardConfig.size === 2 && c.boardConfig.lineLength === 2 && c.board.length === 8, "cubo 1 sube al mínimo 2");
const e = await create({ size: "x", lineLength: null }, "10.9.0.5");
ok(e?.boardConfig.size === 3 && e.boardConfig.lineLength === 3, "valores basura caen al 3 por defecto");
const h = await create({ dimensions: 4, size: 3, lineLength: 3 }, "10.9.0.6");
ok(h?.boardConfig.dimensions === 4 && h.boardConfig.size === 3 && h.board.length === 81, "4D tamaño 3: 81 casillas llegan al cliente");
const h2 = await create({ dimensions: 4, size: 99, lineLength: 99 }, "10.9.0.7");
ok(h2?.boardConfig.dimensions === 4 && h2.boardConfig.size === 6 && h2.board.length === 1296, "4D pidiendo tamaño 99: el servidor lo limita a 6 (1296 casillas)");
const h3 = await create({ dimensions: 2, size: 3, lineLength: 3 }, "10.9.0.8");
ok(h3?.boardConfig.dimensions === 3 && h3.board.length === 27, "dimensión 2D no existe: vuelve a 3D");
const h4 = await create({ dimensions: 7, size: 3, lineLength: 3 }, "10.9.0.9");
ok(h4?.boardConfig.dimensions === 3, "dimensión 7: vuelve a 3D");
const f2 = await create({ fractalLevel: 2, dimensions: 3, size: 3, lineLength: 3 }, "10.9.1.1");
ok(f2?.boardConfig.fractalLevel === 2 && f2.boardConfig.size === 9 && f2.board.length === 729 && f2.board.filter((c) => c === -1).length === 329, "fractal nivel 2: 729 casillas con 329 huecos (-1) llegan al cliente");
const f4 = await create({ fractalLevel: 2, dimensions: 4 }, "10.9.1.2");
ok(f4?.boardConfig.fractalLevel === 1 && f4.board.length === 81 && f4.board.filter((c) => c === -1).length === 9, "fractal 4D pidiendo nivel 2: el servidor lo baja a nivel 1 (81 casillas, 9 huecos)");
const f0 = await create({ fractalLevel: 9 }, "10.9.1.3");
ok(f0?.boardConfig.fractalLevel === 0 && f0.board.filter((c) => c === -1).length === 0, "nivel de fractal inválido: tablero normal sin huecos");
console.log(fails === 0 ? "\nBOARD-WS OK" : `\n${fails} FALLO(S)`); process.exit(fails ? 1 : 0);
